test('A: subtitle result is typed, deduplicated and does not create Chat messages or occupy its slot, including a workspace without Chats', async () => {
  const { name, tasks, target } = await setup();
  const subtitleTarget = { kind: 'subtitle' as const, workspaceId: target.workspaceId, operation: 'translate' as const };
  const job = await tasks.freezeSubtitle({ snapshotId: crypto.randomUUID(), target: subtitleTarget, source: { locator: basis.locator, fingerprint: basis.fingerprint }, targetLanguage: 'en', requirements: '', modelId: 'model-a' }, basis);
  await tasks.freezeChat(target, 1, basis);
  await tasks.attach(job.jobId, job.attempts[0].attemptId, 12);
  const claimed = (await tasks.claim(job.jobId, job.attempts[0].attemptId, 12))!;
  await tasks.checkpoint(job.jobId, job.attempts[0].attemptId, claimed.seq + 1, '', { total: 1, covered: 1, ranges: [{ firstCue: 0, lastCue: 1 }] });
  const cues = [{ from: 0, to: 1, content: 'controlled translation' }, { from: 1, to: 2, content: 'translated last' }];
  await tasks.finish(job.jobId, job.attempts[0].attemptId, 'completed', null, 'subtitle-receipt', { kind: 'subtitle', cues });
  await tasks.finish(job.jobId, job.attempts[0].attemptId, 'completed', null, 'subtitle-receipt', { kind: 'subtitle', cues });
  expect(await tasks.subtitleVersions(target.workspaceId)).toHaveLength(1);
  expect((await tasks.view(subtitleTarget)).messages).toEqual([]);
  expect((await tasks.view(target)).messages.map(m => m.text)).toEqual(['原问题']);
  await new Promise<void>(resolve => { const open = indexedDB.open(name); open.onsuccess = () => { const tx = open.result.transaction('workspaces', 'readwrite'); tx.objectStore('workspaces').put({ id: 'no-chat', source, recentChatId: '', chats: [] }); tx.oncomplete = () => { open.result.close(); resolve(); }; }; });
  const independent = await tasks.freezeSubtitle({ snapshotId: crypto.randomUUID(), target: { ...subtitleTarget, workspaceId: 'no-chat' }, source: { locator: basis.locator, fingerprint: basis.fingerprint }, targetLanguage: 'en', requirements: '', modelId: 'model-a' }, basis);
  expect((await tasks.view(independent.snapshot.target)).messages).toEqual([]);
  await tasks.finish(independent.jobId, independent.attempts[0].attemptId, 'stopped');
  expect(await tasks.subtitleVersions('no-chat')).toEqual([]);
});
test('B: populated v2 migration preserves multiple Chats, all draft fields and revisions', async () => {
  const name = crypto.randomUUID();
  const draft = { schemaVersion: 1, revision: 7, text: '完整草稿', outputType: 'html', template: { templateId: 't', revisionId: 'r' }, referenceIds: ['n'], attachmentIds: ['a'], modelId: 'old-model' };
  const row = { id: 'legacy', source, recentChatId: 'chat-b', chats: [{ id: 'chat-a', title: 'A', draft }, { id: 'chat-b', title: 'B', draft: { ...draft, revision: 9, text: '另一份草稿' } }] };
  await new Promise<void>(resolve => { const open = indexedDB.open(name, 2); open.onupgradeneeded = () => open.result.createObjectStore('workspaces', { keyPath: 'id' }); open.onsuccess = () => { const tx = open.result.transaction('workspaces', 'readwrite'); tx.objectStore('workspaces').put(row); tx.oncomplete = () => { open.result.close(); resolve(); }; }; });
  const store = new IndexedWorkspaceStore(name);
  expect((await store.read('legacy', 'chat-a'))!.draft).toEqual(draft);
  expect(await store.read('legacy')).toMatchObject({ chatId: 'chat-b', chats: [{ id: 'chat-a' }, { id: 'chat-b' }], draft: { revision: 9, text: '另一份草稿' } });
  expect(await new IndexedGenerationStore(name).list()).toEqual([]);
});
