import {expect,test} from '@playwright/test';
import {setup} from './interaction-fixture';
import {mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';

test('library uses the cover-first menu flow, protected default folder, theme tokens and responsive density',async()=>{
  test.setTimeout(60_000);
  const {context,page,site,fixture}=await setup();
  const consoleErrors:string[]=[];
  page.on('console',message=>{if(message.type()==='error')consoleErrors.push(message.text());});
  try{
    const output=resolve('../.tmp/library-redesign');await mkdir(output,{recursive:true});
    const query=()=>page.evaluate(async()=> (await chrome.runtime.sendMessage({version:1,requestId:crypto.randomUUID(),operation:{type:'workspace.query'}})).view);
    for(const id of ['BVlibrary1','BVlibrary2','BVlibrary3','BVlibrary4','BVlibrary5']){
      await site.goto(`https://www.bilibili.com/video/${id}/?p=1`);
      await expect.poll(async()=>(await query()).video?.binding?.videoId,{timeout:10_000}).toBe(id);
      const workspace = await query();
      const saved = await page.evaluate(async workspaceId => chrome.runtime.sendMessage({version:1,requestId:crypto.randomUUID(),operation:{type:'scribble.create',workspaceId,text:'布局验证随笔',time:null}}), workspace.workspaceId);
      expect(saved.ok).toBe(true);
    }
    await page.bringToFront();
    await page.setViewportSize({width:960,height:850});
    await page.getByRole('button',{name:'资料库',exact:true}).click();
    await expect(page.getByRole('heading',{name:'资料库',exact:true})).toBeVisible();
    await expect(page.getByRole('button',{name:'存储管理',exact:true})).toBeVisible();
    await expect(page.getByRole('button',{name:'回收站',exact:true})).toHaveCount(0);
    const search=page.locator('.library-search'),recent=page.getByRole('button',{name:'最近',exact:true}),favorites=page.getByRole('button',{name:'收藏夹',exact:true});
    await expect(recent).toHaveAttribute('title','最近');await expect(favorites).toHaveAttribute('title','收藏夹');
    const [searchBox,recentBox]=await Promise.all([search.boundingBox(),recent.boundingBox()]);
    expect(recentBox!.x).toBeGreaterThan(searchBox!.x+searchBox!.width-1);
    expect(Math.abs(recentBox!.y-searchBox!.y)).toBeLessThan(4);
    await expect(page.getByRole('button',{name:'列表',exact:true})).toHaveCount(0);
    await expect(page.getByRole('button',{name:'网格',exact:true})).toHaveCount(0);
    const card=page.locator('.library-video-card').first();
    await expect(card).toBeVisible();
    await card.getByRole('button',{name:/更多操作/}).click();
    await expect(page.getByRole('menu')).toBeVisible();
    const [menuBox,moreBox]=await Promise.all([page.getByRole('menu').boundingBox(),card.getByRole('button',{name:/更多操作/}).boundingBox()]);
    expect(Math.abs(menuBox!.x-moreBox!.x)).toBeLessThan(180);
    expect(menuBox!.y).toBeGreaterThanOrEqual(moreBox!.y-8);
    expect(menuBox!.y).toBeLessThan(moreBox!.y+moreBox!.height+24);
    await page.screenshot({path:resolve(output,'video-menu.png'),fullPage:true});
    await expect(page.getByRole('menuitem',{name:'收藏',exact:true})).toBeVisible();
    await expect(page.getByRole('menuitem',{name:'添加到文件夹',exact:true})).toBeVisible();
    await expect(page.getByRole('menu').getByRole('button',{name:'删除',exact:true})).toBeVisible();
    await page.getByRole('menuitem',{name:'收藏',exact:true}).click();
    await page.getByRole('button',{name:'收藏夹',exact:true}).click();
    const defaultFolder=page.locator('.library-folder-card').filter({hasText:'默认文件夹'});
    await expect(defaultFolder).toContainText('1 条');
    await defaultFolder.getByRole('button',{name:/更多操作/}).click();
    await expect(page.getByText('默认文件夹不可重命名或删除',{exact:true})).toBeVisible();
    await expect(defaultFolder).toHaveCSS('border-top-style','none');
    await expect(defaultFolder).toHaveCSS('background-color','rgba(0, 0, 0, 0)');
    await page.getByRole('button',{name:'新建文件夹',exact:true}).click();
    await page.screenshot({path:resolve(output,'folder-dialog.png'),fullPage:true});
    await page.getByLabel('文件夹名称').fill('学习资料');
    await page.getByLabel('选择颜色 #8a4de0').click();
    await page.getByRole('button',{name:'创建',exact:true}).click();
    await expect(page.locator('.library-folder-card').filter({hasText:'学习资料'})).toBeVisible();
    await page.getByRole('button',{name:'最近',exact:true}).click();
    await card.getByRole('button',{name:/更多操作/}).click();
    await page.getByRole('menuitem',{name:'添加到文件夹',exact:true}).click();
    await expect(page.getByRole('dialog',{name:'添加到文件夹'})).toBeVisible();
    await page.screenshot({path:resolve(output,'folder-picker.png'),fullPage:true});
    await page.getByLabel('搜索文件夹').fill('学习');
    await expect(page.getByRole('dialog',{name:'添加到文件夹'}).getByRole('button',{name:/学习资料/})).toBeVisible();
    await page.getByRole('dialog',{name:'添加到文件夹'}).getByRole('button',{name:/学习资料/}).click();
    await page.getByRole('dialog',{name:'添加到文件夹'}).getByRole('button',{name:'关闭'}).click();

    await page.setViewportSize({width:960,height:850});
    await expect.poll(()=>page.locator('.library-video-card').first().evaluate(el=>getComputedStyle(el.parentElement!).gridTemplateColumns.split(' ').length)).toBeGreaterThanOrEqual(3);
    await page.screenshot({path:resolve(output,'recent-wide.png'),fullPage:true});
    await page.getByRole('button',{name:'收藏夹',exact:true}).click();
    await page.screenshot({path:resolve(output,'folders-wide.png'),fullPage:true});
    await page.getByRole('button',{name:'最近',exact:true}).click();
    await page.setViewportSize({width:420,height:850});
    await expect.poll(()=>page.locator('.library-video-card').first().evaluate(el=>getComputedStyle(el.parentElement!).gridTemplateColumns.split(' ').length)).toBe(2);
    await page.screenshot({path:resolve(output,'recent-narrow.png'),fullPage:true});
    await card.getByRole('button',{name:/更多操作/}).click();
    const [narrowMenu,narrowMore]=await Promise.all([page.getByRole('menu').boundingBox(),card.getByRole('button',{name:/更多操作/}).boundingBox()]);
    expect(narrowMenu!.y).toBeLessThan(narrowMore!.y+90);
    expect(narrowMenu!.x+narrowMenu!.width).toBeLessThanOrEqual(420);
    await page.screenshot({path:resolve(output,'video-menu-narrow.png'),fullPage:true});
    await card.getByRole('button',{name:/更多操作/}).click();
    await page.getByRole('button',{name:'收藏夹',exact:true}).click();
    await page.screenshot({path:resolve(output,'folders-narrow.png'),fullPage:true});
    await page.getByRole('button',{name:'最近',exact:true}).click();
    await page.setViewportSize({width:280,height:850});
    const cover=page.locator('.library-video-card .library-cover').first();
    await expect.poll(async()=>Math.round((await cover.boundingBox())?.width??0)).toBeLessThanOrEqual(76);
    await page.screenshot({path:resolve(output,'recent-extreme.png'),fullPage:true});
    await page.evaluate(()=>document.documentElement.style.setProperty('--accent','#d74f78'));
    const active=page.getByRole('button',{name:'最近',exact:true});
    const colors=await active.evaluate(el=>({color:getComputedStyle(el).color,background:getComputedStyle(el).backgroundColor}));
    expect(colors.color).not.toBe('rgb(47, 143, 98)');
    expect(colors.background).not.toBe('rgb(234, 245, 239)');
    const unexpectedConsoleErrors=consoleErrors.filter(error=>!error.includes('Failed to load resource: net::ERR_FAILED'));
    expect(unexpectedConsoleErrors).toEqual([]);
    expect(fixture.workspaceId).toBeTruthy();
    await site.bringToFront();
  }finally{await context.close();}
});
