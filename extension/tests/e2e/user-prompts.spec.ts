import {startNewChat} from './workbench-actions';
import { expect, test } from '@playwright/test';
import { setup } from './interaction-fixture';

test('roles live in settings, templates carry data policy, and both freeze into the final request', async () => {
  test.setTimeout(90_000);
  const { context, page, site, worker } = await setup();
  try {
    await page.setViewportSize({ width: 360, height: 850 });
    await worker.evaluate(() => {
      const original = fetch;
      (globalThis as any).promptRequests = [];
      globalThis.fetch = (async (input: any, init: any) => {
        if (!String(input).startsWith('https://api.deepseek.com/')) return original(input, init);
        if (!init?.method || init.method === 'GET') return new Response(JSON.stringify({ object: 'list', data: [{ id: 'local-text', name: 'Local text' }] }), { headers: { 'content-type': 'application/json' } });
        const body = JSON.parse(init.body), planning = String(body.messages[0].content).includes('[P1:requirements-plan]');
        (globalThis as any).promptRequests.push(body);
        const content = planning ? JSON.stringify({ version: 1, interpretedIntent: '生成学习笔记', additionalSources: [], outputRequirements: ['Markdown'] }) : '# 我的学习笔记\n\n任务、角色与资料策略已组合。';
        return new Response('data: ' + JSON.stringify({ choices: [{ index: 0, delta: { content }, finish_reason: 'stop' }] }) + '\n\ndata: [DONE]\n\n', { headers: { 'content-type': 'text/event-stream' } });
      }) as typeof fetch;
    });
    const command = (operation: any) => page.evaluate(operation => chrome.runtime.sendMessage({ version: 1, requestId: crypto.randomUUID(), operation }), operation);
    expect((await command({ type: 'provider.save-key', providerId: 'deepseek', expectedRevision: 0, key: 'SYNTHETIC_LOCAL_ONLY' })).ok).toBe(true);
    const fetched = await command({ type: 'provider.fetch', expectedRevision: 1 });
    expect((await command({ type: 'provider.import-models', expectedRevision: fetched.view.provider.revision, modelIds: ['local-text'] })).ok).toBe(true);
    await page.reload(); await site.bringToFront();
    await startNewChat(page);

    await expect(page.getByLabel('输入区')).not.toContainText('当前对话角色');
    await expect(page.getByLabel('输入区')).not.toContainText('管理角色');
    await expect(page.getByLabel('输入区')).not.toContainText('查看本次 AI 指令');
    await page.getByRole('button', { name: '设置', exact: true }).click();
    const webSwitch=page.getByRole('switch', { name: '新对话默认联网', exact: true });
    await expect(webSwitch).toBeVisible();
    const switchGeometry=async()=>webSwitch.evaluate(element=>{const track=element.getBoundingClientRect(),knob=element.querySelector('i')!.getBoundingClientRect();return{trackLeft:track.left,trackRight:track.right,knobLeft:knob.left,knobRight:knob.right};});
    const offGeometry=await switchGeometry();
    expect(offGeometry.knobLeft-offGeometry.trackLeft).toBeCloseTo(2,0);
    await webSwitch.click();
    await expect(webSwitch).toHaveAttribute('aria-checked','true');
    await expect.poll(async()=>(await switchGeometry()).knobLeft).toBeGreaterThan(offGeometry.knobLeft+10);
    const onGeometry=await switchGeometry();
    expect(onGeometry.knobRight).toBeLessThanOrEqual(onGeometry.trackRight-1);
    await webSwitch.click();
    await expect(webSwitch).toHaveAttribute('aria-checked','false');
    await page.getByRole('button', { name: /角色设置/ }).click();
    await page.getByRole('switch',{name:'将当前角色应用到所有产物',exact:true}).click();
    await page.getByRole('button', { name: '简洁直接', exact: true }).click();
    await page.getByLabel('角色指令', { exact: true }).fill('ROLE_E2E 用耐心的教授口吻详细解释，每章末尾附一处时间区间');
    await page.getByRole('button', { name: '保存角色', exact: true }).click();
    await expect(page.locator('.template-manager').getByRole('status')).toContainText('角色已保存');
    await page.getByRole('button', { name: '复制角色', exact: true }).click();
    await expect(page.getByLabel('角色名称', { exact: true })).toHaveValue('简洁直接 V2');
    await page.getByLabel('角色名称', { exact: true }).fill('临时角色副本');
    await page.getByRole('button', { name: '创建角色', exact: true }).click();
    await page.getByRole('button', { name: '删除角色', exact: true }).click();
    await page.getByRole('button', { name: '确认删除角色', exact: true }).click();
    await expect(page.locator('.template-manager').getByRole('status')).toContainText('角色已从列表删除');
    await page.getByRole('button', { name: /^返回/ }).click();

    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('button', { name: '当前角色', exact: true }).click();
    await page.getByRole('option', { name: /^简洁直接/ }).click();
    await expect(page.getByRole('button', { name: '当前角色', exact: true })).toContainText('简洁直接');
    await page.getByRole('button', { name: '模板工作流', exact: true }).click();
    await page.getByRole('button', { name: /独立阅读文档 · Markdown 笔记/ }).click();
    await page.getByLabel('模板要求', { exact: true }).fill('TASK_E2E 整理关键概念与复习问题');
    await page.locator('summary').filter({ hasText: '资料调用策略' }).click();
    await page.getByRole('switch', { name: '完整主字幕强制使用', exact: true }).check();
    await page.getByRole('button', { name: '保存模板', exact: true }).click();
    await expect(page.locator('.template-manager').getByRole('status')).toContainText('模板已保存');
    await page.getByRole('button', { name: '复制模板', exact: true }).click();
    await expect(page.getByLabel('模板名称', { exact: true })).toHaveValue('独立阅读文档 V2');
    await page.getByLabel('模板名称', { exact: true }).fill('临时模板副本');
    await page.getByRole('button', { name: '创建模板', exact: true }).click();
    await page.getByRole('button', { name: '删除模板', exact: true }).click();
    await page.getByRole('button', { name: '确认删除模板', exact: true }).click();
    await expect(page.locator('.template-manager').getByRole('status').filter({hasText:'模板已从列表删除'})).toContainText('模板已从列表删除');
    await page.getByRole('button', { name: /^返回/ }).click();

    await page.getByLabel('输入草稿').fill('@独立阅读文档');
    await page.locator('#mention-menu').getByRole('button', { name: '独立阅读文档', exact: true }).click();
    await expect(page.getByRole('button', { name: '移除任务模板 独立阅读文档', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '移除任务模板 独立阅读文档', exact: true }).click();
    await expect(page.getByRole('button', { name: '移除任务模板 独立阅读文档', exact: true })).toHaveCount(0);
    await page.getByLabel('输入草稿').fill('@独立阅读文档');
    await page.locator('#mention-menu').getByRole('button', { name: '独立阅读文档', exact: true }).click();
    await page.getByLabel('输入草稿').fill('CURRENT_E2E 请突出易混淆概念');
    await expect(page.getByLabel('输入区')).not.toContainText('角色：');
    await expect(page.getByLabel('输入区')).not.toContainText('模板要求');
    await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 360);
    expect(await worker.evaluate(() => (globalThis as any).promptRequests.length)).toBe(0);
    await page.getByRole('button', { name: '发送', exact: true }).click();
    await expect.poll(() => worker.evaluate(() => (globalThis as any).promptRequests.length),{timeout:30_000}).toBe(2);
    const requests = await worker.evaluate(() => (globalThis as any).promptRequests);
    expect(requests).toHaveLength(2);
    expect(JSON.stringify(requests[0])).not.toContain('ROLE_E2E');
    expect(JSON.stringify(requests[0])).toContain('full_subtitles');
    expect(requests[1].messages[0].content).not.toContain('_E2E');
    for (const text of ['ROLE_E2E', 'TASK_E2E', 'CURRENT_E2E']) expect(JSON.stringify(requests[1].messages.at(-1))).toContain(text);
    expect(requests[1].messages[0].content).toContain('[P1:markdown-output]');
    expect(requests[1].messages[0].content).toContain('[P1:time-links]');
    expect(requests[1].messages.at(-1).content).toContain('每章末尾附一处时间区间');
    expect(requests[1].messages.at(-1).content.trim().endsWith('CURRENT_E2E 请突出易混淆概念')).toBe(true);
    await expect(page.getByRole('button', { name: '打开笔记', exact: true })).toBeVisible({ timeout: 30_000 });
    await expect(page.getByText('已完成', { exact: true })).toBeVisible();
    await expect(page.getByText('本次资料', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'AI 指令', exact: true }).click();
    const inspector = page.getByRole('dialog', { name: '本次 AI 指令', exact: true });
    await expect(inspector).toContainText('实际调用记录 · 不会再次调用模型');
    await expect(inspector).toContainText('P3 · 角色：简洁直接 · v5');
    await expect(inspector).toContainText('P2 · 模板：独立阅读文档 · v6');
    await expect(inspector.getByLabel('选择调用阶段').locator('option')).toHaveCount(2);
    await inspector.getByText('展开请求 JSON', { exact: true }).click();
    const actual = inspector.locator('details').filter({ has: page.getByText('展开请求 JSON', { exact: true }) }).locator('pre');
    expect(JSON.parse((await actual.textContent())!)).toEqual(requests[1]);
    expect(await actual.textContent()).not.toContain('SYNTHETIC_LOCAL_ONLY');
    await inspector.getByRole('button', { name: '关闭指令查看' }).click();

    await page.reload(); await site.bringToFront();
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await expect(page.getByRole('button', { name: '当前角色', exact: true })).toContainText('简洁直接');
    await page.getByRole('button', { name: '当前角色', exact: true }).click();
    await page.getByRole('option', { name: /^默认表达/ }).click();
    await expect(page.getByRole('button', { name: '当前角色', exact: true })).toContainText('默认表达');
  } finally { await context.close(); }
});
